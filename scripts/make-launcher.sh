#!/bin/sh
# Create the Mnemify desktop launcher.
#
#   sh scripts/make-launcher.sh [REPO_ROOT]
#
# macOS  -> ${MNEMIFY_LAUNCHER_DIR:-$HOME/Applications}/Mnemify.app
#           (+ ~/Desktop/Mnemify.app symlink when MNEMIFY_DESKTOP_SHORTCUT=1)
# Linux  -> ${MNEMIFY_LAUNCHER_DIR:-$HOME/.local/share/applications}/mnemify.desktop
#
# The launcher hardcodes the absolute path of this checkout. If you move or
# rename the folder, re-run `sh setup.sh` from the new location to rewrite it.
#
# Safe to run repeatedly: it overwrites what is already there.
#
# POSIX sh — tested with dash and bash. No bashisms.

set -eu

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd -P)
REPO=${1:-$(CDPATH='' cd -- "$SCRIPT_DIR/.." && pwd -P)}
REPO=$(CDPATH='' cd -- "$REPO" && pwd -P)

if [ ! -f "$REPO/mnemify.sh" ]; then
    printf 'make-launcher: %s does not look like a Mnemify checkout.\n' "$REPO" >&2
    exit 1
fi

VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' "$REPO/backend/pyproject.toml" 2>/dev/null | head -1)
[ -n "$VERSION" ] || VERSION="1.0.0"

case "$(uname -s)" in
Darwin)
    APP_DIR=${MNEMIFY_LAUNCHER_DIR:-$HOME/Applications}
    APP="$APP_DIR/Mnemify.app"
    mkdir -p "$APP_DIR"

    # Why an AppleScript applet and not a shell-script bundle (issue #41):
    # checkouts usually live under ~/Documents, ~/Desktop or ~/Downloads, which
    # macOS privacy protection (TCC) guards per app. A bundle whose executable is
    # a script runs as plain /bin/bash, which macOS will not prompt for, so a
    # Finder launch was refused silently (bash exit 126, nothing logged) while
    # the same stub run from Terminal worked on Terminal's access. The applet's
    # executable is a real, signed binary, so macOS attributes the access to
    # "Mnemify" and asks once. osacompile and codesign ship with macOS itself, so
    # no Xcode tools are needed.
    #
    # The applet reads the checkout path from Resources/mnemify-repo, starts
    # mnemify.sh --gui in the background, and quits. The server keeps running
    # and is still attributed to Mnemify. LSUIElement keeps the applet out of
    # the Dock for the second it is alive. The UI is a browser tab.
    BUILD_DIR=$(mktemp -d "$APP_DIR/.mnemify-launcher.XXXXXX")
    trap 'rm -rf "$BUILD_DIR"' EXIT
    NEW_APP="$BUILD_DIR/Mnemify.app"

    # Keep this source ASCII: osacompile does not assume UTF-8 input.
    cat > "$BUILD_DIR/main.applescript" <<'APPLESCRIPT'
-- Mnemify launcher. Generated by scripts/make-launcher.sh; re-run setup.sh to rebuild it.
set repoFile to (POSIX path of (path to me)) & "Contents/Resources/mnemify-repo"
set repo to paragraph 1 of (do shell script "cat " & quoted form of repoFile)
set launcher to repo & "/mnemify.sh"
try
	-- First read of the checkout: this is where macOS asks for folder access.
	do shell script "test -r " & quoted form of launcher
on error
	activate
	display dialog "Mnemify can't open its install folder:" & return & return & repo & return & return & "If you moved or deleted that folder, run setup.sh again from its new location. Otherwise, allow access in System Settings > Privacy & Security > Files & Folders > Mnemify, then open Mnemify again." buttons {"OK"} default button "OK" with icon stop with title "Mnemify"
	return
end try
-- Backgrounded with its output redirected, or do shell script would wait for
-- the server to exit. mnemify.sh --gui writes its own log.
do shell script "/bin/bash " & quoted form of launcher & " --gui >/dev/null 2>&1 &"
APPLESCRIPT
    # osacompile always prints "replacing existing signature"; only show its
    # output when it fails.
    if ! OSA_OUT=$(osacompile -o "$NEW_APP" "$BUILD_DIR/main.applescript" 2>&1); then
        printf 'make-launcher: osacompile failed:\n%s\n' "$OSA_OUT" >&2
        exit 1
    fi

    printf '%s' "$REPO" > "$NEW_APP/Contents/Resources/mnemify-repo"
    rm -f "$NEW_APP/Contents/Resources/applet.icns"
    if [ -f "$REPO/assets/icons/mnemify.icns" ]; then
        cp -f "$REPO/assets/icons/mnemify.icns" "$NEW_APP/Contents/Resources/Mnemify.icns"
    fi

    # No CFBundleVersion on purpose. macOS keys the folder-access grant of an
    # ad-hoc signed app to its exact signature, and the signature covers
    # Info.plist. A version string here would make every update ask again.
    PLIST="$NEW_APP/Contents/Info.plist"
    ACCESS_WHY="Mnemify runs from the folder you installed it in."
    plutil -replace CFBundleIdentifier -string ai.mnemify.app "$PLIST"
    plutil -replace CFBundleName -string Mnemify "$PLIST"
    plutil -replace CFBundleDisplayName -string Mnemify "$PLIST"
    plutil -replace CFBundleIconFile -string Mnemify "$PLIST"
    plutil -remove CFBundleIconName "$PLIST" 2>/dev/null || true
    plutil -replace LSUIElement -bool YES "$PLIST"
    plutil -replace NSDocumentsFolderUsageDescription -string "$ACCESS_WHY" "$PLIST"
    plutil -replace NSDesktopFolderUsageDescription -string "$ACCESS_WHY" "$PLIST"
    plutil -replace NSDownloadsFolderUsageDescription -string "$ACCESS_WHY" "$PLIST"

    # Re-sign after the edits. Apple Silicon refuses to run a bundle whose
    # Info.plist no longer matches its signature.
    if ! SIGN_OUT=$(codesign --force --deep --sign - "$NEW_APP" 2>&1); then
        printf 'make-launcher: codesign failed:\n%s\n' "$SIGN_OUT" >&2
        exit 1
    fi

    # The applet quits as soon as the server is started, so nothing holds the
    # old bundle open and it can simply be swapped out.
    rm -rf "$APP"
    mv "$NEW_APP" "$APP"
    rm -rf "$BUILD_DIR"
    trap - EXIT

    # Nudge Finder/Launchpad into re-reading the bundle so the icon refreshes.
    touch "$APP" 2>/dev/null || true

    printf 'Launcher: %s\n' "$APP"

    # Optional Desktop shortcut: a symlink to the app above. setup.sh asks and
    # sets MNEMIFY_DESKTOP_SHORTCUT=1.
    if [ "${MNEMIFY_DESKTOP_SHORTCUT:-0}" = "1" ]; then
        DESK="$HOME/Desktop/Mnemify.app"
        if [ -L "$DESK" ]; then
            rm -f "$DESK"
        elif [ -d "$DESK" ] && [ "$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$DESK/Contents/Info.plist" 2>/dev/null)" = "ai.mnemify.app" ]; then
            # A copy of an older launcher dragged there by hand. It would
            # still be the broken script-bundle version.
            rm -rf "$DESK"
        fi
        if [ -e "$DESK" ]; then
            printf 'make-launcher: %s already exists and is not a Mnemify launcher. Left it alone.\n' "$DESK" >&2
        else
            ln -s "$APP" "$DESK"
            printf 'Desktop shortcut: %s\n' "$DESK"
        fi
    fi
    printf 'Find it in Launchpad or Spotlight, or in Finder under Go -> Home -> Applications.\n'
    ;;
Linux|*)
    APP_DIR=${MNEMIFY_LAUNCHER_DIR:-$HOME/.local/share/applications}
    DESKTOP="$APP_DIR/mnemify.desktop"
    mkdir -p "$APP_DIR"
    cat > "$DESKTOP" <<DESK
[Desktop Entry]
Type=Application
Version=1.0
Name=Mnemify
GenericName=Knowledge map
Comment=Your knowledge, as a world you can explore
Exec=/bin/bash "$REPO/mnemify.sh" --gui
Icon=$REPO/assets/icons/mnemify-1024.png
Path=$REPO
Terminal=false
# false on purpose: the stub never opens a window of its own (the UI is a
# browser tab), so a startup notification would just spin until it times out.
StartupNotify=false
Categories=Office;Utility;
X-Mnemify-Version=$VERSION
DESK
    chmod 644 "$DESKTOP"
    if command -v update-desktop-database >/dev/null 2>&1; then
        update-desktop-database "$APP_DIR" >/dev/null 2>&1 || true
    fi
    printf 'Launcher: %s\n' "$DESKTOP"
    printf 'Find it in your application menu as "Mnemify" (you may need to log out and back in once).\n'
    ;;
esac
